-- ECOMMERCE DATABASE

BEGIN;

CREATE TABLE IF NOT EXISTS permissions (
    name        VARCHAR(255) PRIMARY KEY,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS roles (
    name        VARCHAR(255) PRIMARY KEY,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_name       VARCHAR(255) NOT NULL,
    permission_name VARCHAR(255) NOT NULL,
    PRIMARY KEY (role_name, permission_name),
    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (role_name) REFERENCES roles(name) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission
        FOREIGN KEY (permission_name) REFERENCES permissions(name) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_role_permissions_permission
    ON role_permissions(permission_name);

CREATE TABLE IF NOT EXISTS users (
    id          VARCHAR(255) PRIMARY KEY,
    username    VARCHAR(255),
    password    VARCHAR(255),
    first_name  VARCHAR(255),
    last_name   VARCHAR(255),
    email       VARCHAR(255),
    birth_date  DATE,
    created_at  DATE,
    modified_at DATE,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id   VARCHAR(255) NOT NULL,
    role_name VARCHAR(255) NOT NULL,
    PRIMARY KEY (user_id, role_name),
    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_name) REFERENCES roles(name) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_user_roles_role ON user_roles(role_name);

CREATE TABLE IF NOT EXISTS invalidate_token (
    id          VARCHAR(255) PRIMARY KEY,
    expiry_time TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_invalidate_token_expiry_time
    ON invalidate_token(expiry_time);

CREATE TABLE IF NOT EXISTS profile (
    id           VARCHAR(255) PRIMARY KEY,
    user_id      VARCHAR(255),
    username     VARCHAR(255),
    first_name   VARCHAR(255),
    last_name    VARCHAR(255),
    phone_number VARCHAR(255),
    email        VARCHAR(255),
    avatar       VARCHAR(255),
    birth_date   DATE
);

CREATE INDEX IF NOT EXISTS idx_profile_user_id ON profile(user_id);

CREATE TABLE IF NOT EXISTS category (
    name        VARCHAR(255) PRIMARY KEY,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS detail (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpu              VARCHAR(255),
    ram              VARCHAR(255),
    storage          VARCHAR(255),
    screen_size      VARCHAR(255),
    battery          VARCHAR(255),
    camera           VARCHAR(255),
    operating_system VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS phone (
    id          VARCHAR(255) PRIMARY KEY,
    name        VARCHAR(255),
    description VARCHAR(255),
    detail_id   BIGINT UNIQUE,
    created_at  DATE,
    CONSTRAINT fk_phone_detail
        FOREIGN KEY (detail_id) REFERENCES detail(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_phone_name ON phone(name);

CREATE TABLE IF NOT EXISTS phone_options (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_id VARCHAR(255) NOT NULL,
    type     VARCHAR(255),
    price    NUMERIC(19, 2),
    color    VARCHAR(255),
    CONSTRAINT fk_phone_options_phone
        FOREIGN KEY (phone_id) REFERENCES phone(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_phone_options_phone_id ON phone_options(phone_id);

CREATE TABLE IF NOT EXISTS phone_images (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_id  VARCHAR(255) NOT NULL,
    image_url VARCHAR(255),
    CONSTRAINT fk_phone_images_phone
        FOREIGN KEY (phone_id) REFERENCES phone(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_phone_images_phone_id ON phone_images(phone_id);

CREATE TABLE IF NOT EXISTS phone_categories (
    phone_id    VARCHAR(255) NOT NULL,
    category_id VARCHAR(255) NOT NULL,
    PRIMARY KEY (phone_id, category_id),
    CONSTRAINT fk_phone_categories_phone
        FOREIGN KEY (phone_id) REFERENCES phone(id) ON DELETE CASCADE,
    CONSTRAINT fk_phone_categories_category
        FOREIGN KEY (category_id) REFERENCES category(name) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_phone_categories_category_id
    ON phone_categories(category_id);

CREATE TABLE IF NOT EXISTS accessory (
    id          VARCHAR(255) PRIMARY KEY,
    name        VARCHAR(255),
    description VARCHAR(255),
    created_at  DATE
);

CREATE INDEX IF NOT EXISTS idx_accessory_name ON accessory(name);

CREATE TABLE IF NOT EXISTS accessory_options (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accessory_id VARCHAR(255) NOT NULL,
    type         VARCHAR(255),
    price        VARCHAR(255),
    CONSTRAINT fk_accessory_options_accessory
        FOREIGN KEY (accessory_id) REFERENCES accessory(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_accessory_options_accessory_id
    ON accessory_options(accessory_id);

CREATE TABLE IF NOT EXISTS accessory_images (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accessory_id VARCHAR(255) NOT NULL,
    image_url    VARCHAR(255),
    CONSTRAINT fk_accessory_images_accessory
        FOREIGN KEY (accessory_id) REFERENCES accessory(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_accessory_images_accessory_id
    ON accessory_images(accessory_id);

CREATE TABLE IF NOT EXISTS accessory_category (
    accessory_id VARCHAR(255) NOT NULL,
    category_id  VARCHAR(255) NOT NULL,
    PRIMARY KEY (accessory_id, category_id),
    CONSTRAINT fk_accessory_category_accessory
        FOREIGN KEY (accessory_id) REFERENCES accessory(id) ON DELETE CASCADE,
    CONSTRAINT fk_accessory_category_category
        FOREIGN KEY (category_id) REFERENCES category(name) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_accessory_category_category_id
    ON accessory_category(category_id);

CREATE TABLE IF NOT EXISTS inventory_phone (
    id                  VARCHAR(255) PRIMARY KEY,
    product_id          VARCHAR(255) NOT NULL,
    name                VARCHAR(255),
    quantity            INTEGER NOT NULL DEFAULT 0,
    reserved_quantity   INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER NOT NULL DEFAULT 5,
    status              VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    version             BIGINT NOT NULL DEFAULT 0,
    created_at          TIMESTAMP(6) WITH TIME ZONE,
    updated_at          TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_inventory_phone_product_id UNIQUE (product_id),
    CONSTRAINT ck_inventory_phone_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_inventory_phone_reserved_quantity CHECK (reserved_quantity >= 0 AND reserved_quantity <= quantity),
    CONSTRAINT ck_inventory_phone_low_stock_threshold CHECK (low_stock_threshold >= 0),
    CONSTRAINT fk_inventory_phone_product
        FOREIGN KEY (product_id) REFERENCES phone(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_inventory_phone_status ON inventory_phone(status);
CREATE INDEX IF NOT EXISTS idx_inventory_phone_stock_level
    ON inventory_phone(quantity, reserved_quantity, low_stock_threshold);

CREATE TABLE IF NOT EXISTS inventory_phone_images (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_phone_id  VARCHAR(255) NOT NULL,
    image_url           VARCHAR(255),
    CONSTRAINT fk_inventory_phone_images_inventory
        FOREIGN KEY (inventory_phone_id) REFERENCES inventory_phone(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_inventory_phone_images_inventory_id
    ON inventory_phone_images(inventory_phone_id);

CREATE TABLE IF NOT EXISTS inventory_accessory (
    id                  VARCHAR(255) PRIMARY KEY,
    product_id          VARCHAR(255) NOT NULL,
    name                VARCHAR(255),
    quantity            INTEGER NOT NULL DEFAULT 0,
    reserved_quantity   INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER NOT NULL DEFAULT 5,
    status              VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    version             BIGINT NOT NULL DEFAULT 0,
    created_at          TIMESTAMP(6) WITH TIME ZONE,
    updated_at          TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_inventory_accessory_product_id UNIQUE (product_id),
    CONSTRAINT ck_inventory_accessory_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_inventory_accessory_reserved_quantity CHECK (reserved_quantity >= 0 AND reserved_quantity <= quantity),
    CONSTRAINT ck_inventory_accessory_low_stock_threshold CHECK (low_stock_threshold >= 0),
    CONSTRAINT fk_inventory_accessory_product
        FOREIGN KEY (product_id) REFERENCES accessory(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_inventory_accessory_status
    ON inventory_accessory(status);
CREATE INDEX IF NOT EXISTS idx_inventory_accessory_stock_level
    ON inventory_accessory(quantity, reserved_quantity, low_stock_threshold);

CREATE TABLE IF NOT EXISTS inventory_accessory_images (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_accessory_id VARCHAR(255) NOT NULL,
    image_url              VARCHAR(255),
    CONSTRAINT fk_inventory_accessory_images_inventory
        FOREIGN KEY (inventory_accessory_id) REFERENCES inventory_accessory(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_inventory_accessory_images_inventory_id
    ON inventory_accessory_images(inventory_accessory_id);

COMMIT;
